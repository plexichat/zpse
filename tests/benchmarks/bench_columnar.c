/* ------------------------------------------------------------------ *
 * `stats`: which predictors does the encoder actually trial, and how often
 * per searched tile?
 *
 * This exists because a predictor's classify cost says nothing about its
 * share of encode time unless the encoder asks for it, and that is not
 * observable from outside the library. Built with -DZPSE_TRIAL_STATS the
 * library keeps two counters (tile.c / segment.c) and this mode prints them
 * per corpus case, over exactly the corpora the shootout below uses. Same
 * corpus, same block size, same entry point -- so the counts are the ones
 * the throughput rows pay for.
 *
 * The denominator is SEARCHED tiles: tiles written by the all-hit run or
 * the repeat cache never reach the predictor search, so counting them would
 * understate the true per-tile trial rate.
 *
 * Round-trip is verified before the counters are read, so a case whose
 * stream changed cannot be reported as a win.
 * ------------------------------------------------------------------ */
#if defined(ZPSE_TRIAL_STATS)
extern uint32_t zpse_trial_calls[12];
extern uint32_t zpse_trial_search_tiles;
extern uint32_t zpse_stats_palettable;
extern uint32_t zpse_stats_palette_emits;
extern uint32_t zpse_stats_literal_emits;
extern uint32_t zpse_stats_modes[64];

static const char *const pred_names[12] = {
    "CONST_ZERO", "LANE_PREVIOUS", "LANE_DELTA", "ORDER1",
    "ORDER2", "STRIDE_1", "STRIDE_2", "STRIDE_4",
    "STRIDE_8", "TILE_CONSTANT", "LANE_AVERAGE", "STRIDE_3"
};

static int run_trial_stats(const char *only)
{
    const int nc = (int)(sizeof cases / sizeof cases[0]);
    uint32_t total[12] = {0};
    uint32_t total_tiles = 0;
    int i, p;

    printf("trial stats: predictors CLASSIFIED (candidate attempts) per "
           "corpus case\n");
    printf("corpus: %zu x %zu KiB blocks of the shootout's own generators\n",
           g_nb, g_blk / 1024u);
    printf("| case | searched tiles | trials | per tile | palettable | "
           "palette | literal | %s |\n", "busiest three");
    printf("|---|---:|---:|---:|---:|---:|---:|---|\n");
    for (i = 0; i < nc; i++) {
        uint32_t before[12];
        uint32_t got[12];
        uint32_t tiles0, tiles, ntr = 0;
        uint32_t pal0, pemit0, lemit0, pal_n, pemit_n, lemit_n;
        size_t b;
        int k;

        if (only[0] && !strstr(cases[i].name, only))
            continue;
        g_rng = 0x1234u + (uint32_t)i * 7919u;
        cases[i].gen();
        for (p = 0; p < 12; p++)
            before[p] = zpse_trial_calls[p];
        tiles0 = zpse_trial_search_tiles;
        pal0 = zpse_stats_palettable;
        pemit0 = zpse_stats_palette_emits;
        lemit0 = zpse_stats_literal_emits;
        for (b = 0; b < g_nb; b++) {
            uint8_t *src = g_in + b * g_blk;
            size_t cn = z_comp(src, g_blk, g_comp, g_blk + 1024u);
            if (cn == 0 || cn > g_blk + 1024u) {
                printf("| %s | compress failed |\n", cases[i].name);
                return 1;
            }
            if (z_decomp(g_comp, cn, g_out, g_blk) != 0 ||
                memcmp(g_out, src, g_blk) != 0) {
                printf("| %s | round-trip FAILED |\n", cases[i].name);
                return 1;
            }
        }
        tiles = zpse_trial_search_tiles - tiles0;
        pal_n = zpse_stats_palettable - pal0;
        pemit_n = zpse_stats_palette_emits - pemit0;
        lemit_n = zpse_stats_literal_emits - lemit0;
        for (p = 0; p < 12; p++) {
            got[p] = zpse_trial_calls[p] - before[p];
            ntr += got[p];
            total[p] += got[p];
        }
        total_tiles += tiles;
        /* Busiest three of this case, by count. */
        {
            int b1 = -1, b2 = -1, b3 = -1;
            char busy[128];
            int ord[12];
            int n = 0;

            for (p = 0; p < 12; p++)
                ord[n++] = p;
            for (k = 1; k < n; k++) { /* insertion sort, descending */
                int v = ord[k];
                int j = k - 1;
                while (j >= 0 && got[ord[j]] < got[v]) {
                    ord[j + 1] = ord[j];
                    j--;
                }
                ord[j + 1] = v;
            }
            b1 = ord[0]; b2 = ord[1]; b3 = ord[2];
            snprintf(busy, sizeof busy, "%s %u, %s %u, %s %u",
                     pred_names[b1], (unsigned)got[b1],
                     pred_names[b2], (unsigned)got[b2],
                     pred_names[b3], (unsigned)got[b3]);
            printf("| %s | %u | %u | %.2f | %u | %u | %u | %s |\n",
                   cases[i].name, (unsigned)tiles, (unsigned)ntr,
                   tiles ? (double)ntr / (double)tiles : 0.0,
                   (unsigned)pal_n, (unsigned)pemit_n, (unsigned)lemit_n,
                   busy);
        }
    }
    printf("\npredictor totals over every case (share of all trials):\n");
    printf("| predictor | id | trials | share |\n|---|---:|---:|---:|\n");
    {
        uint32_t all = 0u;

        for (p = 0; p < 12; p++)
            all += total[p];
        for (p = 0; p < 12; p++) {
            printf("| %s | %d | %u | %.1f%% |\n", pred_names[p], p,
                   (unsigned)total[p],
                   all ? 100.0 * (double)total[p] / (double)all : 0.0);
        }
        printf("| **searched tiles** | | %u | trials/tile %.2f |\n",
               (unsigned)total_tiles,
               total_tiles ? (double)all / (double)total_tiles : 0.0);
    }
    /* Which (mask_mode, res_mode) pairs the mode search picks. A classify
     * produces three per-exception arrays but a packed record reads one
     * array per mode, so this is what decides whether producing all three
     * is worth it. */
    {
        uint32_t mtot = 0u;

        for (p = 0; p < 64; p++)
            mtot += zpse_stats_modes[p];
        printf("\nmode pairs chosen (mask_mode / res_mode), %u tiles:\n",
               (unsigned)mtot);
        printf("| mask | res | tiles | share |\n|---:|---:|---:|---:|\n");
        for (p = 0; p < 64; p++) {
            if (zpse_stats_modes[p] == 0u)
                continue;
            printf("| %d | %d | %u | %.1f%% |\n", p >> 3, p & 7,
                   (unsigned)zpse_stats_modes[p],
                   mtot ? 100.0 * (double)zpse_stats_modes[p] / (double)mtot
                        : 0.0);
        }
    }
    return 0;
}
#else
static int run_trial_stats(const char *only)
{
    (void)only;
    printf("stats mode needs a build defining ZPSE_TRIAL_STATS:\n"
           "  cc -std=c11 -O2 -DZPSE_TRIAL_STATS -Iinclude \\\n"
           "     tests/benchmarks/bench_columnar.c src/zpse_unity.c -ldl \\\n"
           "     -o /tmp/benchcol && /tmp/benchcol stats\n");
    return 2;
}
#endif /* ZPSE_TRIAL_STATS */

int main(int argc, char **argv)
{
    const int nc = (int)(sizeof cases / sizeof cases[0]);
    int iters = argc > 1 ? atoi(argv[1]) : 30;
    int reps = argc > 2 ? atoi(argv[2]) : 5;
    const char *only = (argc > 3 && strcmp(argv[3], "all") != 0) ? argv[3] : "";
    const char *onlyc = (argc > 4 && strcmp(argv[4], "all") != 0) ? argv[4] : "";
    Codec codecs[5];
    /* per-codec summary accumulators: mean ratio / encode / decode */
    double sum_ratio[5] = { 0, 0, 0, 0, 0 };
    double sum_enc[5] = { 0, 0, 0, 0, 0 };
    double sum_dec[5] = { 0, 0, 0, 0, 0 };
    int sum_n[5] = { 0, 0, 0, 0, 0 };
    int i, c, r;
    long blk_kb = argc > 5 ? atol(argv[5]) : 64L;
    /* ZPSE_ENC_* options for the zpse rows; 0 is the default sweep. */
    g_enc_flags = argc > 6 ? (uint32_t)strtoul(argv[6], NULL, 0) : 0u;

    if (iters < 1) iters = 1;
    if (reps < 1) reps = 1;
    if (reps > 32) reps = 32;
    /* optional per-block-size reporting: corpus stays 4 MiB, count scales */
    if (blk_kb != 16L && blk_kb != 32L && blk_kb != 64L &&
        blk_kb != 128L && blk_kb != 256L) {
        printf("bad blk_kb %ld: want 16/32/64/128/256\n", blk_kb);
        return 2;
    }
    g_blk = (size_t)blk_kb * 1024u;
    g_nb = CORPUS / g_blk;

    g_in = malloc(CSIZE);
    g_comp = malloc(g_blk * 2 + 4096u);
    g_out = malloc(g_blk);
    if (!g_in || !g_comp || !g_out) { printf("oom\n"); return 1; }
    /* `stats [case]`: predictor trial accounting instead of the shootout.
     * Needs -DZPSE_TRIAL_STATS (see run_trial_stats). */
    if (argc > 1 && strcmp(argv[1], "stats") == 0) {
        return run_trial_stats(argc > 2 && strcmp(argv[2], "all") != 0
                                   ? argv[2]
                                   : "");
    }
    load_all();

    codecs[0] = (Codec){ "zpse","default",1,z_cbound,z_comp,z_decomp };
    codecs[1] = (Codec){ "zstd","-3",
        h_zstd && p_ZSTD_compress && p_ZSTD_decompress &&
        p_ZSTD_compressBound && p_ZSTD_isError, zs_cbound, zs_comp, zs_decomp };
    codecs[2] = (Codec){ "lz4","fast",
        h_lz4 && p_LZ4_compress_default && p_LZ4_decompress_safe &&
        p_LZ4_compressBound, lz_cbound, lz_comp, lz_decomp };
    codecs[3] = (Codec){ "zlib","-6",
        h_z && p_compress2 && p_uncompress, zl_cbound, zl_comp, zl_decomp };
    codecs[4] = (Codec){ "brotli","q5",
        h_bre && h_brd && p_BrotliEncoderCompress &&
        p_BrotliDecoderDecompress && p_BrotliEncoderMaxCompressedSize,
        br_cbound, br_comp, br_decomp };

    setvbuf(stdout, NULL, _IONBF, 0);
    print_host();
    printf("columnar in-process: 4 MiB/case as %zux%zu KiB blocks, single core, "
           "best(med/max)-of-%d reps\n", g_nb, g_blk / 1024u, reps);
    printf("levels: zpse default, zstd -3, lz4 fast, zlib -6, brotli q5; "
           "identical bytes per codec, every decode verified\n");
    printf("zpse encoder: enc_flags=0x%lx speed=%s%s\n",
           (unsigned long)g_enc_flags,
           (g_enc_flags & ZPSE_ENC_SPEED_MASK) == (uint32_t)ZPSE_ENC_FASTER
               ? "FASTER"
               : (g_enc_flags & ZPSE_ENC_SPEED_MASK) ==
                         (uint32_t)ZPSE_ENC_FASTEST
                     ? "FASTEST"
                     : (g_enc_flags & ZPSE_ENC_SPEED_MASK) ==
                               (uint32_t)ZPSE_ENC_MAX
                           ? "MAX"
                           : "BALANCED",
           (g_enc_flags & ZPSE_ENC_CHECKSUM) ? " +CHECKSUM" : "");
    printf("versions: zpse %s | zstd %s | lz4 %s | zlib %s | brotli %u.%u.%u\n",
           zpse_version_string(),
           p_ZSTD_versionString ? p_ZSTD_versionString() : "n/a",
           p_LZ4_versionString ? p_LZ4_versionString() : "n/a",
           p_zlibVersion ? p_zlibVersion() : "n/a",
           p_BrotliEncoderVersion ? (p_BrotliEncoderVersion() >> 24) & 255u : 0u,
           p_BrotliEncoderVersion ? (p_BrotliEncoderVersion() >> 16) & 255u : 0u,
           p_BrotliEncoderVersion ? (p_BrotliEncoderVersion() >> 8) & 255u : 0u);
    {
        const char *miss[4];
        int nmiss = 0, k;
        if (!codecs[1].ok) miss[nmiss++] = "zstd";
        if (!codecs[2].ok) miss[nmiss++] = "lz4";
        if (!codecs[3].ok) miss[nmiss++] = "zlib";
        if (!codecs[4].ok) {
            miss[nmiss++] = (h_bre || h_brd) ? "brotli(partial)" : "brotli";
        }
        if (nmiss > 0) {
            printf("skip: ");
            for (k = 0; k < nmiss; k++)
                printf("%s%s", miss[k], k + 1 < nmiss ? ", " : "");
            printf(" runtime missing, those cells omitted (never zeroed)\n");
        }
    }
    printf("| case | codec | ratio | encode best(med/max) | decode best(med/max) | eff |\n");
    printf("|---|---|---:|---|---:|---:|\n");
    for (i = 0; i < nc; i++) {
        if (only[0] && !strstr(cases[i].name, only)) continue;
        g_rng = 0x1234u + (uint32_t)i * 7919u;
        cases[i].gen();
        uint64_t tcount[12] = { 0 };
        for (c = 0; c < 5; c++) {
            Codec *k = &codecs[c];
            size_t tot_c = 0, worst = 0, *clens;
            /* per-rep per-block ns: best = headline, med = typical,
             * max = jitter signal. cap 32 reps (clamped above). */
            double erep[32], drep[32];
            int nrep = 0;
            double be_ns, med_e, max_e, bd_ns, med_d, max_d;
            double enc_mb, med_enc_mb, max_enc_mb;
            double dec_mb, med_dec_mb, max_dec_mb;
            double ratio, eff;
            size_t b;
            int fail = 0;
            int myiters = iters;
            int slow;
            if (!k->ok) continue;
            if (onlyc[0] && !strstr(k->name, onlyc)) continue;
            /* slow codecs get fewer timed iters; ratio is unaffected */
            slow = (k == &codecs[3] || k == &codecs[4]);
            if (slow) myiters = (iters + 3) / 4;
            worst = k->cbound(g_blk);
            clens = malloc(sizeof(size_t) * g_nb);
            if (!clens) { printf("oom\n"); return 1; }
            for (b = 0; b < g_nb; b++) {
                size_t cl = k->comp(g_in + b * g_blk, g_blk, g_comp, worst);
                if (!cl) { fail = 1; break; }
                if (k->decomp(g_comp, cl, g_out, g_blk) != 0 ||
                    memcmp(g_out, g_in + b * g_blk, g_blk) != 0) { fail = 1; break; }
                clens[b] = cl; tot_c += cl;
                if (k == &codecs[0]) {
                    ZpseBlockHeader bh;
                    if (zpse_block_header_parse(&bh, g_comp, ZPSE_BLOCK_HEADER_SIZE) == 0 &&
                        bh.transform_id < 12u) tcount[bh.transform_id]++;
                }
            }
            if (fail) {
                printf("| %s | %s | FAILED | - | - | - |\n", cases[i].name, k->name);
                free(clens); continue;
            }
            for (r = 0; r < reps; r++) {
                double t0 = now_ns(), t1, e_ns;
                double s0, s1, dsum = 0.0;
                int dmul = myiters * (slow ? 3 : 10);
                for (b = 0; b < g_nb; b++)
                    for (int t = 0; t < myiters; t++)
                        k->comp(g_in + b * g_blk, g_blk, g_comp, worst);
                t1 = now_ns();
                e_ns = (t1 - t0) / ((double)g_nb * myiters);
                for (b = 0; b < g_nb; b++) {
                    /* re-encode to restore the verified bytes, then time
                     * the decode of exactly those bytes */
                    k->comp(g_in + b * g_blk, g_blk, g_comp, worst);
                    s0 = now_ns();
                    for (int t = 0; t < dmul; t++)
                        k->decomp(g_comp, clens[b], g_out, g_blk);
                    s1 = now_ns();
                    dsum += (s1 - s0) / dmul;
                }
                erep[r] = e_ns;
                drep[r] = dsum / (double)g_nb;
                nrep++;
            }
            be_ns = erep[0]; max_e = erep[0];
            bd_ns = drep[0]; max_d = drep[0];
            for (r = 1; r < nrep; r++) {
                if (erep[r] < be_ns) be_ns = erep[r];
                if (erep[r] > max_e) max_e = erep[r];
                if (drep[r] < bd_ns) bd_ns = drep[r];
                if (drep[r] > max_d) max_d = drep[r];
            }
            med_e = med_of(erep, nrep);
            med_d = med_of(drep, nrep);
            {
                char rb[16], eb[32], mb_e[24], xb_e[24];
                char db[32], mb_d[24], xb_d[24], fb[24];
                enc_mb = (double)g_blk * 1000.0 / be_ns;
                med_enc_mb = (double)g_blk * 1000.0 / med_e;
                max_enc_mb = (double)g_blk * 1000.0 / max_e;
                dec_mb = (double)g_blk * 1000.0 / bd_ns;
                med_dec_mb = (double)g_blk * 1000.0 / med_d;
                max_dec_mb = (double)g_blk * 1000.0 / max_d;
                ratio = ratio_of(CSIZE, tot_c);
                eff = ratio * enc_mb;
                fmt_ratio(rb, sizeof rb, CSIZE, tot_c);
                fmt_rate(eb, sizeof eb, enc_mb);
                fmt_rate(mb_e, sizeof mb_e, med_enc_mb);
                fmt_rate(xb_e, sizeof xb_e, max_enc_mb);
                fmt_rate(db, sizeof db, dec_mb);
                fmt_rate(mb_d, sizeof mb_d, med_dec_mb);
                fmt_rate(xb_d, sizeof xb_d, max_dec_mb);
                snprintf(fb, sizeof fb, "%.0f", eff);
                printf("| %s | %s %s | %s | %s (%s/%s) | %s (%s/%s) | %s |\n",
                       cases[i].name, k->name, k->level, rb,
                       eb, mb_e, xb_e, db, mb_d, xb_d, fb);
                if (k == &codecs[0]) {
                    char tbuf[160];
                    size_t tb = 0;
                    int first = 1, t;
                    for (t = 0; t < 12; t++) {
                        if (tcount[t]) {
                            if (!first) tbuf[tb++] = ' ';
                            first = 0;
                            tb += (size_t)snprintf(tbuf + tb, sizeof tbuf - tb,
                                                   "%s=%llu", tname[t],
                                                   (unsigned long long)tcount[t]);
                        }
                    }
                    if (first) snprintf(tbuf, sizeof tbuf, "(no blocks)");
                    printf("transforms(%s): %s\n", cases[i].name, tbuf);
                }
                sum_ratio[c] += ratio;
                sum_enc[c] += enc_mb;
                sum_dec[c] += dec_mb;
                sum_n[c]++;
            }
            free(clens);
        }
    }
    printf("\nsummary (mean across run cases; encode vs decode split):\n");
    printf("| codec | cases | mean ratio | mean encode | mean decode |\n");
    printf("|---|---|---:|---:|---:|\n");
    for (c = 0; c < 5; c++) {
        if (sum_n[c] == 0) continue;
        {
            char rb[16], eb[24], db[24];
            double mr = sum_ratio[c] / sum_n[c];
            snprintf(rb, sizeof rb, "%.2f:1", mr);
            fmt_rate(eb, sizeof eb, sum_enc[c] / sum_n[c]);
            fmt_rate(db, sizeof db, sum_dec[c] / sum_n[c]);
            printf("| %s %s | %d | %s | %s | %s |\n",
                   codecs[c].name, codecs[c].level, sum_n[c], rb, eb, db);
        }
    }
    free(g_in); free(g_comp); free(g_out);
    return 0;
}

