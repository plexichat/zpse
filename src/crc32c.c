static uint32_t zpse_crc32c_slice8(uint32_t crc, const uint8_t *p, size_t len)
{
    while (len >= 8u) {
        uint32_t v;

        /* The reflected CRC consumes a word's bytes least-significant first,
         * so this unaligned load must present p[0] as the low byte even on a
         * big-endian target -- that is the byte order the explicit four-byte
         * construction it replaced produced. */
        memcpy(&v, p, 4);
#if defined(__BYTE_ORDER__) && (__BYTE_ORDER__ == __ORDER_BIG_ENDIAN__)
        v = __builtin_bswap32(v);
#endif
        crc ^= v;
        crc = zpse_crc32c_s8[6][crc & 0xFFu] ^
              zpse_crc32c_s8[5][(crc >> 8) & 0xFFu] ^
              zpse_crc32c_s8[4][(crc >> 16) & 0xFFu] ^
              zpse_crc32c_s8[3][(crc >> 24) & 0xFFu] ^
              zpse_crc32c_s8[2][p[4]] ^
              zpse_crc32c_s8[1][p[5]] ^
              zpse_crc32c_s8[0][p[6]] ^
              zpse_crc32c_table[p[7]];
        p += 8;
        len -= 8;
    }
    return crc;
}

/* ------------------------------------------------------------------ *
 * SSE4.2 hardware `crc32` path.  One 64-bit chain: 8 bytes per
 * instruction, 3-cycle latency floor => ~2.67 B/cycle sustained.
 *
 * That is a LATENCY bound, not a throughput bound: the chain cannot
 * issue faster than one `crc32` per 3 cycles no matter how wide the
 * core is.  So anything sizeable is split into three contiguous chunks
 * driven by three crc32 chains that are stepped inside ONE loop -- the
 * three instructions are independent, so the core issues them back to
 * back and the same 3 cycles now retire 24 bytes instead of 8.  (Three
 * chains run as three separate loops would be no faster than one: each
 * loop is still serialised against its own chain latency.)  The chunks
 * are contiguous rather than interleaved so every stream still walks
 * memory forwards, and they stay inside the block, which is at most
 * 64 KiB and therefore cache-resident.
 *
 * Sewing the chunks back together needs the GF(2) "append L zero
 * bytes" operator below.
 * ------------------------------------------------------------------ */
#if (defined(__x86_64__) || defined(_M_X64)) && ZPSE_CRC32C_HW
#define ZPSE_CRC32C_HAVE_HW 1
#else
#define ZPSE_CRC32C_HAVE_HW 0
#endif

#if ZPSE_CRC32C_HAVE_HW
#if defined(_MSC_VER)
#include <intrin.h>
#define ZPSE_CRC32C_TARGET
static int zpse_crc32c_hw_cached = -1; /* -1 = not yet computed */
static int zpse_crc32c_hw_cached_get(void)
{
    return zpse_crc32c_hw_cached;
}
static void zpse_crc32c_hw_cached_set(int v)
{
    zpse_crc32c_hw_cached = v;
}
#else
#include <cpuid.h>
#include <smmintrin.h>
#define ZPSE_CRC32C_TARGET __attribute__((target("sse4.2")))
#include <stdatomic.h>
static _Atomic int zpse_crc32c_hw_cached = -1;
/* Relaxed atomics, exactly as vector.h's ZPSE_CPU_CAPS_FAST() cache: the
 * computation is idempotent, so racing first callers all store the same
 * answer and no one needs a barrier on the hot path. */
static int zpse_crc32c_hw_cached_get(void)
{
    return atomic_load_explicit(&zpse_crc32c_hw_cached, memory_order_relaxed);
}
static void zpse_crc32c_hw_cached_set(int v)
{
    atomic_store_explicit(&zpse_crc32c_hw_cached, v, memory_order_relaxed);
}
#endif

static int zpse_crc32c_hw_present(void)
{
    /* CPUID is serialising (microseconds under virtualisation) and this is
     * asked on every CRC and every fused copy+checksum -- twice per block
     * in both directions just for the 14-byte page header -- so the answer
     * is computed once and cached, as with zpse_cpu_caps().
     *
     * ZPSE_CPU_CAPS_FAST() is the process-wide CPUID cache and is the
     * first gate. ZpseCpuCaps has no SSE4.2 bit (only SSE2/SSSE3/AVX2/
     * AVX512/NEON), so cpu_caps() cannot answer this question directly;
     * the one-time probe below reads ECX.20 and caches the bit locally in
     * the same call-once style. Using the caps word as gate means
     * ZPSE_FORCE_SCALAR (caps == 0) and non-x86 builds skip the probe
     * altogether, and the hot path stays a single relaxed load -- no call
     * into vector.c and no second CPUID. */
    int present = zpse_crc32c_hw_cached_get();

    if (present >= 0) {
        return present;
    }
    if (ZPSE_CPU_CAPS_FAST() == 0u) {
        present = 0;
    } else {
#if defined(_MSC_VER)
        int info[4];

        __cpuid(info, 1);
        present = (info[2] >> 20) & 1;
#else
        unsigned int a = 0;
        unsigned int b = 0;
        unsigned int c = 0;
        unsigned int d = 0;

        present = 0;
        if (__get_cpuid(1, &a, &b, &c, &d)) {
            present = (int)((c >> 20) & 1u);
        }
#endif
    }
    zpse_crc32c_hw_cached_set(present);
    return present;
}
#endif /* ZPSE_CRC32C_HAVE_HW */

/* ---- GF(2) zero-byte operator (zlib's crc32_combine recipe) --------
 *
 * The chain is a state machine over bytes: raw(I, X||Y) =
 * raw(raw(I, X), Y).  For the reflected CRC, "append L zero bytes" is a
 * linear map S(., 8L) on the 32-bit state, which is what lets chunks
 * computed by independent chains be sewn back together.
 *
 * A map is 32 rows of 32 bits over GF(2); row n is the image of the
 * state with only bit n set, and applying it is an XOR of the selected
 * rows.  Row 0 is the reflected polynomial (state shifted down by one
 * with the polynomial fed in) and row n is bit n-1, i.e. the plain shift
 * -- squaring builds "two zero bits", "four", "eight", and so on.
 *
 * The powers-of-two-byte operators depend only on the polynomial and
 * never change, so they are a static const table below, generated at
 * source time by the same three squarings followed by repeated squaring.
 * No lazy growth and no shared mutable state: per call only the small
 * conditional apply loop costs anything, and every worker sees the same
 * immutable operators.
 */
#if defined(_MSC_VER)
#include <intrin.h> /* _BitScanForward, used by zpse_crc32c_ctz32 below */
#endif

/* Index of the lowest set bit of a nonzero word. Every caller loops only
 * while vec != 0, so neither intrinsic is ever asked about zero. */
static unsigned zpse_crc32c_ctz32(uint32_t x)
{
#if defined(_MSC_VER)
    unsigned long index;

    _BitScanForward(&index, (unsigned long)x);
    return (unsigned)index;
#else
    return (unsigned)__builtin_ctz(x);
#endif
}

static uint32_t zpse_crc32c_gf2_times(const uint32_t mat[32], uint32_t vec)
{
    uint32_t sum = 0u;

    /* One iteration per set bit, not per bit position. XOR is commutative,
     * so walking the set bits low-to-high selects exactly the same rows as
     * the old shift-and-test loop (and gives a bit-identical result). */
    while (vec != 0u) {
        sum ^= mat[zpse_crc32c_ctz32(vec)];
        vec &= vec - 1u;
    }
    return sum;
}

